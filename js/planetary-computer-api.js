/**
 * Microsoft Planetary Computer URL API middleware.
 *
 * Resolves a tile URL copied straight out of the Planetary Computer's data
 * API (https://planetarycomputer.microsoft.com/docs/reference/stac/, the
 * "tiles" links on a STAC Item/mosaic) into a `tms` layer config — with a
 * title/attribution built from the STAC item it points at instead of the
 * generic "Raster Layer" fallback every other unrecognized `/{z}/{x}/{y}`
 * URL gets (see `guessLayerType`/`makeLayerConfig` in layer-source-resolver.js).
 *
 * Recognized URL shapes (all under planetarycomputer.microsoft.com):
 *   /api/data/v1/item/tiles/<tileMatrixSet>/{z}/{x}/{y}?collection=...&item=...
 *   /api/data/v1/collection/tiles/<tileMatrixSet>/{z}/{x}/{y}?collection=...
 *   /api/data/v1/mosaic/<search-id>/tiles/<tileMatrixSet>/{z}/{x}/{y}?collection=...&assets=...
 * A trailing `@2x`/`@3x`/`@4x` retina suffix on the `{y}` segment (as seen in
 * links generated by the Explorer) is preserved as-is.
 *
 * Mosaic URLs are not copy-pasted from the Explorer — they come from
 * registering a STAC search against `POST /api/data/v1/mosaic/register`
 * (body: `collections`, `bbox`, `datetime`, `query`, `sortby`), which returns
 * a search id. The resulting tile URL renders the best-matching item per
 * tile across that whole search (e.g. "most recent low-cloud Landsat scene")
 * instead of one fixed STAC item, and requires a `collection` query param on
 * the tile request itself (the search id alone is not enough).
 *
 * A layer resolved this way carries a `pcMosaicSearch` field (collections/
 * query/sortby, deliberately without `bbox` — see createConfigFromTileUrl)
 * that `js/mapbox-api.js` uses to re-register the search with a new
 * `datetime` range whenever js/time-control.js's range inputs change. Set
 * `pcMosaicSearch.viewportBbox: true` (by hand, in the layer's config) to
 * additionally re-register on every pan/zoom using the current map viewport
 * as `bbox` instead of a fixed area — see MapboxAPI._setupMosaicViewportListener.
 */
const PC_HOST = 'planetarycomputer.microsoft.com';
const PC_DATA_BASE = 'https://planetarycomputer.microsoft.com/api/data/v1';
const PC_STAC_BASE = 'https://planetarycomputer.microsoft.com/api/stac/v1';
const PC_EXPLORER_BASE = 'https://planetarycomputer.microsoft.com/explore';

function formatLabel(text) {
    if (!text) return '';
    return text.replace(/[-_]+/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}

// Turns a concrete single-tile URL (as copy-pasted from a Planetary Computer
// tile link, e.g. `.../11/1480/949@2x?collection=...`) into the `{z}/{x}/{y}`
// XYZ template a `tms` layer's `url` needs — any `@2x`-style retina suffix on
// the y segment is preserved rather than templated over.
function toTileTemplate(url) {
    return url.replace(/\/\d+\/\d+\/\d+(@[1-4]x)?($|\?)/i, (match, retina, end) => `/{z}/{x}/{y}${retina || ''}${end}`);
}

export class PlanetaryComputerAPI {
    static isTileUrl(url) {
        if (!url || typeof url !== 'string') return false;
        try {
            const parsed = new URL(url);
            return parsed.hostname === PC_HOST &&
                /^\/api\/data\/v1\/(?:item\/tiles\/|collection\/tiles\/|mosaic\/[^/]+\/tiles\/)/.test(parsed.pathname);
        } catch (error) {
            return false;
        }
    }

    static parseTileUrl(url) {
        const parsed = new URL(url);
        const params = parsed.searchParams;
        const mosaicMatch = parsed.pathname.match(/^\/api\/data\/v1\/mosaic\/([^/]+)\/tiles\//);
        return {
            kind: mosaicMatch ? 'mosaic' : (/^\/api\/data\/v1\/collection\/tiles\//.test(parsed.pathname) ? 'collection' : 'item'),
            searchId: mosaicMatch ? mosaicMatch[1] : null,
            collection: params.get('collection'),
            item: params.get('item'),
            assets: params.get('assets')
        };
    }

    static buildExplorerUrl({ kind, collection, item }) {
        const params = new URLSearchParams();
        if (collection) params.set('collection', collection);
        // The Explorer has no URL-addressable view for a registered mosaic search id.
        if (kind !== 'mosaic' && item) params.set('item', item);
        return `${PC_EXPLORER_BASE}?${params.toString()}`;
    }

    /** Best-effort fetch of the source STAC item — used only to enrich the
     * title/description/bbox; a failed or missing fetch still resolves. */
    static async fetchItem(collection, item) {
        if (!collection || !item) return null;
        try {
            const response = await fetch(`${PC_STAC_BASE}/collections/${collection}/items/${item}`);
            if (!response.ok) return null;
            return await response.json();
        } catch (error) {
            console.warn('[PlanetaryComputer] Failed to fetch STAC item:', error);
            return null;
        }
    }

    /** Best-effort fetch of the registered search behind a mosaic search id —
     * used only to enrich the title/description/bbox; a failed or missing
     * fetch still resolves. */
    static async fetchMosaicInfo(searchId) {
        if (!searchId) return null;
        try {
            const response = await fetch(`${PC_DATA_BASE}/mosaic/${searchId}/info`);
            if (!response.ok) return null;
            return await response.json();
        } catch (error) {
            console.warn('[PlanetaryComputer] Failed to fetch mosaic info:', error);
            return null;
        }
    }

    static buildTitle(parsed, stacItem, mosaicInfo) {
        const { collection, assets, kind } = parsed;
        const parts = [];
        if (kind === 'mosaic') {
            const search = mosaicInfo?.search?.search;
            if (search?.datetime) parts.push(`[${search.datetime}]`);
            parts.push(formatLabel(collection) || 'Planetary Computer Layer');
            parts.push('(Mosaic)');
        } else {
            const datetime = stacItem?.properties?.datetime;
            if (datetime) parts.push(`[${datetime.slice(0, 10)}]`);
            parts.push(formatLabel(stacItem?.collection || collection) || 'Planetary Computer Layer');
        }
        const firstAsset = assets ? assets.split(',')[0].trim() : null;
        if (firstAsset) parts.push(`(${formatLabel(firstAsset)})`);
        return parts.join(' ');
    }

    static buildDescription(parsed, mosaicInfo) {
        const { kind, collection, item } = parsed;
        if (kind === 'mosaic') {
            if (!collection) return null;
            const search = mosaicInfo?.search?.search;
            const bits = [`Mosaic over <code>${collection}</code>`];
            if (search?.datetime) bits.push(`datetime <code>${search.datetime}</code>`);
            if (search?.query) bits.push(`query <code>${JSON.stringify(search.query)}</code>`);
            return `${bits.join(', ')}.`;
        }
        if (!item || !collection) return null;
        return `STAC item <code>${item}</code> from the <code>${collection}</code> collection.`;
    }

    static buildAttribution(parsed) {
        const explorerUrl = this.buildExplorerUrl(parsed);
        return `<a href='${explorerUrl}' target='_blank' rel='noopener noreferrer'>Microsoft Planetary Computer</a>`;
    }

    /** Resolves a Planetary Computer tile URL into a `tms` layer config. */
    static async createConfigFromTileUrl(url) {
        const parsed = this.parseTileUrl(url);
        const stacItem = parsed.kind === 'item' ? await this.fetchItem(parsed.collection, parsed.item) : null;
        const mosaicInfo = parsed.kind === 'mosaic' ? await this.fetchMosaicInfo(parsed.searchId) : null;
        const mosaicSearch = mosaicInfo?.search?.search;

        const idBase = (parsed.item || parsed.searchId || parsed.collection || 'planetary-computer')
            .toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40);
        const bbox = Array.isArray(stacItem?.bbox) && stacItem.bbox.length === 4
            ? stacItem.bbox
            : (Array.isArray(mosaicSearch?.bbox) && mosaicSearch.bbox.length === 4 ? mosaicSearch.bbox : null);
        const description = this.buildDescription(parsed, mosaicInfo);

        // Lets time-control.js re-register this search with a new `datetime`
        // range (see MapboxAPI._registerPlanetaryComputerMosaicRange) instead
        // of being pinned to the range in place when the URL was pasted.
        // `bbox` is deliberately omitted here even when the search had one —
        // it's already captured by the layer's own top-level `bbox` above,
        // and MapboxAPI falls back to that when re-registering.
        const pcMosaicSearch = parsed.kind === 'mosaic' && mosaicSearch ? {
            collections: mosaicSearch.collections,
            ...(mosaicSearch.query && { query: mosaicSearch.query }),
            ...(mosaicSearch.sortby && { sortby: mosaicSearch.sortby })
        } : null;

        return {
            id: `pc-${idBase}-${Math.floor(Math.random() * 90) + 10}`,
            type: 'tms',
            title: this.buildTitle(parsed, stacItem, mosaicInfo),
            url: toTileTemplate(url),
            attribution: this.buildAttribution(parsed),
            initiallyChecked: false,
            ...(description && { description }),
            ...(bbox && { bbox }),
            ...(pcMosaicSearch && { pcMosaicSearch })
        };
    }
}
