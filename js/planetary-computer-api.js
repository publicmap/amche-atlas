/**
 * Microsoft Planetary Computer URL API middleware.
 *
 * Resolves a tile URL copied straight out of the Planetary Computer's data
 * API (https://planetarycomputer.microsoft.com/docs/reference/stac/, the
 * "tiles" links on a STAC Item/mosaic) into a `tms` layer config — with a
 * title/attribution built from the STAC item it points at instead of the
 * generic "Raster Layer" fallback every other unrecognized `/{z}/{x}/{y}`
 * URL gets (see `guessLayerType`/`makeLayerConfig` in layer-source-resolver.js).
 *
 * Recognized URL shapes (all under planetarycomputer.microsoft.com):
 *   /api/data/v1/item/tiles/<tileMatrixSet>/{z}/{x}/{y}?collection=...&item=...
 *   /api/data/v1/collection/tiles/<tileMatrixSet>/{z}/{x}/{y}?collection=...
 *   /api/data/v1/mosaic/tiles/<search-id>/{z}/{x}/{y}?...
 * A trailing `@2x`/`@3x`/`@4x` retina suffix on the `{y}` segment (as seen in
 * links generated by the Explorer) is preserved as-is.
 */
const PC_HOST = 'planetarycomputer.microsoft.com';
const PC_STAC_BASE = 'https://planetarycomputer.microsoft.com/api/stac/v1';
const PC_EXPLORER_BASE = 'https://planetarycomputer.microsoft.com/explore';

function formatLabel(text) {
    if (!text) return '';
    return text.replace(/[-_]+/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}

// Turns a concrete single-tile URL (as copy-pasted from a Planetary Computer
// tile link, e.g. `.../11/1480/949@2x?collection=...`) into the `{z}/{x}/{y}`
// XYZ template a `tms` layer's `url` needs — any `@2x`-style retina suffix on
// the y segment is preserved rather than templated over.
function toTileTemplate(url) {
    return url.replace(/\/\d+\/\d+\/\d+(@[1-4]x)?($|\?)/i, (match, retina, end) => `/{z}/{x}/{y}${retina || ''}${end}`);
}

export class PlanetaryComputerAPI {
    static isTileUrl(url) {
        if (!url || typeof url !== 'string') return false;
        try {
            const parsed = new URL(url);
            return parsed.hostname === PC_HOST &&
                /^\/api\/data\/v1\/(item|collection|mosaic)\/tiles\//.test(parsed.pathname);
        } catch (error) {
            return false;
        }
    }

    static parseTileUrl(url) {
        const parsed = new URL(url);
        const params = parsed.searchParams;
        return {
            collection: params.get('collection'),
            item: params.get('item'),
            assets: params.get('assets')
        };
    }

    static buildExplorerUrl({ collection, item }) {
        const params = new URLSearchParams();
        if (collection) params.set('collection', collection);
        if (item) params.set('item', item);
        return `${PC_EXPLORER_BASE}?${params.toString()}`;
    }

    /** Best-effort fetch of the source STAC item — used only to enrich the
     * title/description/bbox; a failed or missing fetch still resolves. */
    static async fetchItem(collection, item) {
        if (!collection || !item) return null;
        try {
            const response = await fetch(`${PC_STAC_BASE}/collections/${collection}/items/${item}`);
            if (!response.ok) return null;
            return await response.json();
        } catch (error) {
            console.warn('[PlanetaryComputer] Failed to fetch STAC item:', error);
            return null;
        }
    }

    static buildTitle({ collection, assets }, stacItem) {
        const parts = [];
        const datetime = stacItem?.properties?.datetime;
        if (datetime) parts.push(`[${datetime.slice(0, 10)}]`);
        parts.push(formatLabel(stacItem?.collection || collection) || 'Planetary Computer Layer');
        const firstAsset = assets ? assets.split(',')[0].trim() : null;
        if (firstAsset) parts.push(`(${formatLabel(firstAsset)})`);
        return parts.join(' ');
    }

    static buildDescription({ collection, item }) {
        if (!item || !collection) return null;
        return `STAC item <code>${item}</code> from the <code>${collection}</code> collection.`;
    }

    static buildAttribution({ collection, item }) {
        const explorerUrl = this.buildExplorerUrl({ collection, item });
        return `<a href='${explorerUrl}' target='_blank' rel='noopener noreferrer'>Microsoft Planetary Computer</a>`;
    }

    /** Resolves a Planetary Computer tile URL into a `tms` layer config. */
    static async createConfigFromTileUrl(url) {
        const parsed = this.parseTileUrl(url);
        const stacItem = await this.fetchItem(parsed.collection, parsed.item);

        const idBase = (parsed.item || parsed.collection || 'planetary-computer')
            .toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40);
        const bbox = Array.isArray(stacItem?.bbox) && stacItem.bbox.length === 4 ? stacItem.bbox : null;
        const description = this.buildDescription(parsed);

        return {
            id: `pc-${idBase}-${Math.floor(Math.random() * 90) + 10}`,
            type: 'tms',
            title: this.buildTitle(parsed, stacItem),
            url: toTileTemplate(url),
            attribution: this.buildAttribution(parsed),
            initiallyChecked: false,
            ...(description && { description }),
            ...(bbox && { bbox })
        };
    }
}
